"""Builds every Osprey Launcher brand image from one place.

Writes:
  assets/icon/osprey-launcher.svg   master icon (1024 x 1024, transparent corners)
  assets/icon/osprey-launcher.png   1024 x 1024
  assets/icon/osprey-launcher.ico   16-256 px, PNG-encoded (Windows)
  assets/icon/osprey-launcher.icns  16-1024 px including @2x (macOS)
  osprey_launcher/app_icon.py       the master SVG as a string, used for the window icon
  assets/banner.png                 README banner, 1280 x 320 drawn at 2x (2560 x 640)
  assets/social-card.png            GitHub social preview, 1280 x 640 (fixed repo-card layout)

Run from the project root with the project's environment:
  .venv/bin/python assets/make_assets.py
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path

from PySide6.QtCore import QBuffer, QByteArray, QIODevice, QPointF, QRectF, Qt
from PySide6.QtGui import (
    QColor,
    QFont,
    QFontDatabase,
    QFontMetrics,
    QGuiApplication,
    QImage,
    QPainter,
    QPen,
)
from PySide6.QtSvg import QSvgRenderer

ROOT = Path(__file__).resolve().parent.parent
ICON_DIR = ROOT / "assets" / "icon"
NAME = "osprey-launcher"

# Colours from osprey_launcher/theme.py (dark palette) plus two deeper steps of the accent.
ACCENT = "#5cbfb3"
ACCENT_MID = "#3f9a8f"
ACCENT_DEEP = "#2a6a63"
TILE_TOP = "#232326"
TILE_BOTTOM = "#141415"
DEEP = "#0f0f10"  # theme "deep": the darkest background
TEXT = "#ededed"  # theme "t1"
TEXT_2 = "#a1a1a6"  # theme "t2"
TEXT_3 = "#85858b"  # theme "t3"
BORDER = QColor(237, 237, 237, 20)  # theme "hl"

APP_NAME = "Osprey Launcher"
TAGLINE = "Apps, files and links. One Launcher."
SUBLINE = "Windows · macOS · Linux"
SANS = ["Segoe UI", "Inter", "SF Pro Display", "Helvetica Neue", "Arial"]
MONO = ["Cascadia Mono", "Consolas", "SF Mono", "Menlo", "DejaVu Sans Mono"]


def icon_svg() -> str:
    """Three rising chevrons on a graphite tile. The tile follows the macOS icon grid."""
    chevrons = "".join(
        f'<path d="M332 {y + 120} L512 {y} L692 {y + 120}" fill="none" stroke="{colour}" '
        'stroke-width="72" stroke-linecap="round" stroke-linejoin="round"/>'
        for y, colour in ((300, ACCENT), (450, ACCENT_MID), (600, ACCENT_DEEP))
    )
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">'
        '<defs><linearGradient id="tile" x1="0" y1="0" x2="0" y2="1">'
        f'<stop offset="0" stop-color="{TILE_TOP}"/><stop offset="1" stop-color="{TILE_BOTTOM}"/>'
        "</linearGradient></defs>"
        '<rect x="100" y="100" width="824" height="824" rx="185" fill="url(#tile)"/>'
        '<rect x="102" y="102" width="820" height="820" rx="183" fill="none" '
        'stroke="#ffffff" stroke-opacity="0.08" stroke-width="4"/>'
        f"{chevrons}</svg>"
    )


def render(svg: str, size: int) -> QImage:
    image = QImage(size, size, QImage.Format_ARGB32_Premultiplied)
    image.fill(Qt.transparent)
    painter = QPainter(image)
    painter.setRenderHint(QPainter.Antialiasing)
    QSvgRenderer(QByteArray(svg.encode())).render(painter, QRectF(0, 0, size, size))
    painter.end()
    return image


def png_bytes(image: QImage) -> bytes:
    buffer = QBuffer()
    buffer.open(QIODevice.WriteOnly)
    image.save(buffer, "PNG")
    return bytes(buffer.data())


def write_ico(svg: str, path: Path) -> None:
    sizes = (16, 20, 24, 32, 40, 48, 64, 128, 256)
    images = [png_bytes(render(svg, s)) for s in sizes]
    header = struct.pack("<HHH", 0, 1, len(sizes))
    offset = 6 + 16 * len(sizes)
    entries = b""
    for size, data in zip(sizes, images):
        dim = 0 if size == 256 else size
        entries += struct.pack("<BBBBHHII", dim, dim, 0, 0, 1, 32, len(data), offset)
        offset += len(data)
    path.write_bytes(header + entries + b"".join(images))


def write_icns(svg: str, path: Path) -> None:
    types = (
        ("icp4", 16),
        ("icp5", 32),
        ("icp6", 64),
        ("ic07", 128),
        ("ic08", 256),
        ("ic09", 512),
        ("ic10", 1024),
        ("ic11", 32),
        ("ic12", 64),
        ("ic13", 256),
        ("ic14", 512),
    )
    chunks = b""
    for code, size in types:
        data = png_bytes(render(svg, size))
        chunks += code.encode() + struct.pack(">I", 8 + len(data)) + data
    path.write_bytes(b"icns" + struct.pack(">I", 8 + len(chunks)) + chunks)


def write_app_icon_module(svg: str) -> None:
    module = (
        '"""The app icon as an SVG string. Generated by assets/make_assets.py; do not edit."""\n\n'
        f"APP_ICON_SVG = {svg!r}\n"
    )
    (ROOT / "osprey_launcher" / "app_icon.py").write_text(module, encoding="utf-8")


def font(families: list, pixel_size: int, weight: QFont.Weight) -> QFont:
    available = set(QFontDatabase.families())
    result = QFont()
    result.setFamilies([f for f in families if f in available] or families)
    result.setPixelSize(pixel_size)
    result.setWeight(weight)
    return result


def fit(base: QFont, text: str, max_width: float) -> QFont:
    """Shrink the font 2 px at a time until the text, ink included, fits max_width."""
    result = QFont(base)

    def width(f: QFont) -> int:
        metrics = QFontMetrics(f)
        ink = metrics.tightBoundingRect(text)
        return max(metrics.horizontalAdvance(text), ink.right()) - min(0, ink.left())

    while width(result) > max_width - 8 and result.pixelSize() > 12:
        result.setPixelSize(result.pixelSize() - 2)
    return result


def banner(svg: str, scale: int = 2) -> QImage:
    """Rounded darkest-background panel; icon left, name and tagline right, centred as one group."""
    w, h = 1280 * scale, 320 * scale
    image = QImage(w, h, QImage.Format_ARGB32_Premultiplied)
    image.fill(Qt.transparent)
    painter = QPainter(image)
    painter.setRenderHint(QPainter.Antialiasing)
    painter.setRenderHint(QPainter.TextAntialiasing)
    half = scale / 2
    painter.setPen(QPen(BORDER, scale))
    painter.setBrush(QColor(DEEP))
    painter.drawRoundedRect(
        QRectF(half, half, w - scale, h - scale), 24 * scale, 24 * scale
    )

    icon_size, gap = 176 * scale, 40 * scale
    name_font = font(SANS, 96 * scale, QFont.DemiBold)
    tag_font = font(MONO, 24 * scale, QFont.Normal)
    name_m, tag_m = QFontMetrics(name_font), QFontMetrics(tag_font)
    text_w = max(name_m.horizontalAdvance(APP_NAME), tag_m.horizontalAdvance(TAGLINE))
    left = (w - (icon_size + gap + text_w)) / 2
    painter.drawImage(
        QRectF(left, (h - icon_size) / 2, icon_size, icon_size), render(svg, icon_size)
    )

    line_gap = 52 * scale
    block = name_m.capHeight() + line_gap + tag_m.capHeight()
    name_base = (h - block) / 2 + name_m.capHeight()
    x = left + icon_size + gap
    painter.setFont(name_font)
    painter.setPen(QColor(TEXT))
    painter.drawText(QPointF(x, name_base), APP_NAME)
    painter.setFont(tag_font)
    painter.setPen(QColor(TEXT_2))
    painter.drawText(
        QPointF(x + scale * 2, name_base + line_gap + tag_m.capHeight()), TAGLINE
    )
    painter.end()
    return image


# Social card: fixed repo-card layout, same values as the standard template script.
CARD_W, CARD_H, CARD_SAFE = 1280, 640, 80
CARD_ICON, CARD_ICON_TOP, CARD_ICON_GAP = 168, 150, 40
CARD_NAME_PX, CARD_NAME_SPACING = 112, 98
CARD_TAG_PX, CARD_TAG_BASE = 34, 420
CARD_SUB_PX, CARD_SUB_BASE = 24, 476


def social_card(svg: str) -> QImage:
    image = QImage(CARD_W, CARD_H, QImage.Format_ARGB32)
    image.fill(QColor(DEEP))
    painter = QPainter(image)
    painter.setRenderHint(QPainter.Antialiasing)
    painter.setRenderHint(QPainter.TextAntialiasing)
    safe_w = CARD_W - 2 * CARD_SAFE

    name_font = font(SANS, CARD_NAME_PX, QFont.DemiBold)
    name_font.setLetterSpacing(QFont.PercentageSpacing, CARD_NAME_SPACING)
    icon_part = CARD_ICON + CARD_ICON_GAP
    name_font = fit(name_font, APP_NAME, safe_w - icon_part)
    name_w = QFontMetrics(name_font).horizontalAdvance(APP_NAME)
    left = (CARD_W - (icon_part + name_w)) / 2
    QSvgRenderer(QByteArray(svg.encode())).render(
        painter, QRectF(left, CARD_ICON_TOP, CARD_ICON, CARD_ICON)
    )
    cap = QFontMetrics(name_font).capHeight()
    painter.setFont(name_font)
    painter.setPen(QColor(TEXT))
    nudge = name_font.pixelSize() * 0.035
    painter.drawText(
        QPointF(left + icon_part - nudge, CARD_ICON_TOP + CARD_ICON / 2 + cap / 2),
        APP_NAME,
    )

    for text, px, colour, y in (
        (TAGLINE, CARD_TAG_PX, TEXT_2, CARD_TAG_BASE),
        (SUBLINE, CARD_SUB_PX, TEXT_3, CARD_SUB_BASE),
    ):
        text_font = fit(font(MONO, px, QFont.Normal), text, safe_w)
        painter.setFont(text_font)
        painter.setPen(QColor(colour))
        x = (CARD_W - QFontMetrics(text_font).horizontalAdvance(text)) / 2
        painter.drawText(QPointF(x, y), text)
    painter.end()
    return image


def main() -> int:
    app = QGuiApplication.instance() or QGuiApplication(sys.argv)  # noqa: F841
    ICON_DIR.mkdir(parents=True, exist_ok=True)
    svg = icon_svg()
    (ICON_DIR / f"{NAME}.svg").write_text(svg, encoding="utf-8")
    render(svg, 1024).save(str(ICON_DIR / f"{NAME}.png"))
    write_ico(svg, ICON_DIR / f"{NAME}.ico")
    write_icns(svg, ICON_DIR / f"{NAME}.icns")
    write_app_icon_module(svg)
    banner(svg).save(str(ROOT / "assets" / "banner.png"))
    social_card(svg).save(str(ROOT / "assets" / "social-card.png"))
    print(
        "Wrote assets/icon/*, osprey_launcher/app_icon.py, assets/banner.png, assets/social-card.png"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
